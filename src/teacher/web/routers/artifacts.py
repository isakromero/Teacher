"""Artifact endpoints: create (and generate in the background), list, show, runs, regenerate, delete.

Artifacts come in two families. Study pages (and any other block-based kind) are generated by
`app.state.generator`; labs (`kind = "lab"`, see `teacher.labs`) by `app.state.lab_generator`.
A lab is never created here (`POST /api/artifacts` with kind "lab" is a 422): it is made from a
study page with `POST /api/artifacts/{slug}/labs` (`teacher.web.routers.labs`). The other
endpoints work for both: a lab's `progress` counts its checked steps as gates
(`total_blocks` is 0, since a lab has no blocks), and regenerating a lab keeps its
`params.study_page`, which must still be a ready study page.

After a study page's generation, when the app has a review bank builder
(`app.state.review_bank_builder`), the same background job builds the page's review variants
(`teacher.review_bank.build_after_generation`, a `review_bank` run); a failure there leaves the
page as it is.
"""

from __future__ import annotations

from typing import Annotated, Any

from fastapi import APIRouter, BackgroundTasks, Body, HTTPException, Query, Request
from fastapi.responses import Response
from pydantic import BaseModel, ConfigDict, Field, field_validator
from sqlalchemy import select
from sqlalchemy.orm import Session

from teacher.config import GENERATION_MODEL_CHOICES, Settings
from teacher.db.models import Artifact, GenerationRun, KnowledgeSource
from teacher.files import slugify, validate_slug
from teacher.generation import MODEL_PARAM, run_generation, supports_model_choice
from teacher.labs import LAB_KIND, STUDY_PAGE_KIND, STUDY_PAGE_PARAM, LabKindError
from teacher.managers import (
    ArtifactManager,
    GenerationRunManager,
    KnowledgeSourceManager,
    LabManager,
    NotFoundError,
    StudyHistoryManager,
)
from teacher.managers.artifacts import DEFAULT_ROLE
from teacher.reading import reading_state
from teacher.review_bank import build_after_generation
from teacher.web.common import to_iso
from teacher.web.deps import SessionDep, SettingsDep
from teacher.web.errors import _scrub_paths

router = APIRouter(prefix="/api", tags=["artifacts"])

DEFAULT_KIND = STUDY_PAGE_KIND


# -- request models -----------------------------------------------------------------------


class ArtifactCreate(BaseModel):
    model_config = ConfigDict(extra="forbid")

    sources: list[str] = Field(min_length=1)
    kind: str = DEFAULT_KIND
    title: str | None = None
    slug: str | None = None
    params: dict[str, Any] = Field(default_factory=dict)
    model: str | None = None  # the model to generate with; the configured default if omitted

    @field_validator("sources")
    @classmethod
    def _unique(cls, value: list[str]) -> list[str]:
        if len(set(value)) != len(value):
            raise ValueError("sources must not repeat")
        return value

    @field_validator("kind")
    @classmethod
    def _not_a_lab(cls, value: str) -> str:
        if value == LAB_KIND:
            raise ValueError(
                "a lab is made from a ready study page: POST /api/artifacts/{slug}/labs"
            )
        return value


class RegenerateIn(BaseModel):
    model_config = ConfigDict(extra="forbid")

    params: dict[str, Any] | None = None
    model: str | None = None  # the model for the new version; the old version's if omitted


# -- response models ----------------------------------------------------------------------


class ArtifactSourceOut(BaseModel):
    slug: str
    title: str
    role: str


class ProgressOut(BaseModel):
    total_blocks: int
    gates_total: int
    gates_cleared: int
    complete: bool


class TokensOut(BaseModel):
    input: int
    output: int


class ArtifactOut(BaseModel):
    slug: str
    kind: str
    title: str
    summary: str | None
    status: str
    generator: str
    model: str | None  # the model chosen for this artifact; null means the configured default
    params: dict[str, Any]
    created_at: str
    supersedes: str | None
    superseded_by: str | None
    sources: list[ArtifactSourceOut]
    progress: ProgressOut
    tokens: TokensOut


class ModelChoiceOut(BaseModel):
    id: str
    label: str


class GenerationModelsOut(BaseModel):
    selectable: bool  # false: the configured generator cannot be given a model
    default: str
    models: list[ModelChoiceOut]


class RunOut(BaseModel):
    id: int
    stage: str
    model: str
    status: str
    input_tokens: int | None
    output_tokens: int | None
    error: str | None
    note: str | None  # something to know about a stage that succeeded
    started_at: str
    finished_at: str | None


# -- helpers ------------------------------------------------------------------------------


def _lab_progress(session: Session, settings: Settings, artifact: Artifact) -> ProgressOut:
    """A lab's progress: its checked steps are its gates, cleared once a check passed. A lab
    that is not ready has no spec yet, so nothing to count."""
    if artifact.status != "ready":
        return ProgressOut(total_blocks=0, gates_total=0, gates_cleared=0, complete=False)
    manager = LabManager(session, settings)
    spec = manager.spec(artifact)
    checked = [
        status for status in manager.step_statuses(artifact, spec)
        if spec.steps[status.index].check is not None
    ]
    cleared = sum(1 for status in checked if status.passed)
    return ProgressOut(
        total_blocks=0,
        gates_total=len(checked),
        gates_cleared=cleared,
        complete=cleared == len(checked),
    )


def _progress(
    session: Session, settings: Settings, artifact: Artifact, max_attempts: int
) -> ProgressOut:
    """Gate progress, from the same gating rules the reading endpoints use (a lab's: see
    `_lab_progress`)."""
    if artifact.kind == LAB_KIND:
        return _lab_progress(session, settings, artifact)
    summary = reading_state(session, settings, artifact, max_attempts=max_attempts).summary()
    return ProgressOut(
        total_blocks=summary["total_blocks"],
        gates_total=summary["gates_total"],
        gates_cleared=summary["gates_cleared"],
        complete=artifact.status == "ready" and summary["complete"],
    )


def artifact_out(
    session: Session, settings: Settings, artifact: Artifact, max_attempts: int
) -> ArtifactOut:
    manager = ArtifactManager(session, settings)
    successors = artifact.superseded_by
    tokens_in, tokens_out = GenerationRunManager(session, settings).token_totals(artifact)
    return ArtifactOut(
        slug=artifact.slug,
        kind=artifact.kind,
        title=artifact.title,
        summary=artifact.summary,
        status=artifact.status,
        generator=artifact.generator,
        model=(artifact.params or {}).get(MODEL_PARAM),
        params=dict(artifact.params or {}),
        created_at=to_iso(artifact.created_at),
        supersedes=artifact.supersedes.slug if artifact.supersedes is not None else None,
        superseded_by=successors[-1].slug if successors else None,
        sources=[
            ArtifactSourceOut(slug=source.slug, title=source.title, role=role)
            for source, role in manager.sources(artifact)
        ],
        progress=_progress(session, settings, artifact, max_attempts),
        tokens=TokensOut(input=tokens_in, output=tokens_out),
    )


def run_out(run: GenerationRun, settings: Settings) -> RunOut:
    return RunOut(
        id=run.id,
        stage=run.stage,
        model=run.model,
        status=run.status,
        input_tokens=run.input_tokens,
        output_tokens=run.output_tokens,
        error=_scrub_paths(run.error, settings.root) if run.error else run.error,
        note=run.note,
        started_at=to_iso(run.started_at),
        finished_at=to_iso(run.finished_at),
    )


def _slug_taken(session: Session, settings: Settings, slug: str) -> bool:
    row = session.scalar(select(Artifact.id).where(Artifact.slug == slug))
    return row is not None or (settings.artifacts_dir / slug).exists()


def unique_slug(session: Session, settings: Settings, base: str) -> str:
    """`base` if free, else `base-2`, `base-3`, ... (checks rows and folders)."""
    validate_slug(base)
    slug, n = base, 1
    while _slug_taken(session, settings, slug):
        n += 1
        slug = f"{base}-{n}"
    return slug


def _lineage_root(artifact: Artifact) -> Artifact:
    """The oldest artifact still present in the `supersedes` chain of `artifact`."""
    seen = {artifact.id}
    while artifact.supersedes is not None and artifact.supersedes.id not in seen:
        artifact = artifact.supersedes
        seen.add(artifact.id)
    return artifact


def _require_not_generating(artifact: Artifact) -> None:
    if artifact.status == "generating":
        raise HTTPException(409, f"artifact {artifact.slug!r} is still generating")


def generator_for(state: Any, kind: str) -> Any:
    """The generator for an artifact of `kind`: the lab generator for labs, else the study
    page generator (`app.state`)."""
    return state.lab_generator if kind == LAB_KIND else state.generator


def lab_study_page(
    session: Session, settings: Settings, slug: str, *, for_lab: str | None = None
) -> Artifact:
    """The study page `slug` a lab is (to be) made from: 404 if missing, 422 if not a study
    page, 409 unless ready. `for_lab` names the lab whose study page it is, for the 404."""
    try:
        page = ArtifactManager(session, settings).get_by_slug(slug)
    except NotFoundError:
        if for_lab is None:
            raise
        raise NotFoundError(f"the study page {slug!r} of lab {for_lab!r} no longer exists") from None
    if page.kind != STUDY_PAGE_KIND:
        raise LabKindError(
            f"artifact {slug!r} is a {page.kind}, not a study page; labs are made from study pages"
        )
    if page.status != "ready":
        raise HTTPException(409, f"the study page {slug!r} is {page.status}, not ready")
    return page


def generation_models(generator: Any) -> GenerationModelsOut:
    """The models an artifact may be generated with: the fixed choices plus the configured
    default when it is not one of them. Empty when the generator cannot be given a model."""
    if not supports_model_choice(generator):
        return GenerationModelsOut(selectable=False, default=generator.model, models=[])
    models = [ModelChoiceOut(id=id_, label=label) for id_, label in GENERATION_MODEL_CHOICES]
    if generator.model not in {choice.id for choice in models}:
        models.append(ModelChoiceOut(id=generator.model, label=generator.model))
    return GenerationModelsOut(selectable=True, default=generator.model, models=models)


def _params_with_model(
    generator: Any, params: dict[str, Any], model: str | None
) -> dict[str, Any]:
    """`params` with the requested `model` stored under `model`; ValueError (422) for a model
    that is not offered, or for any model when the generator cannot be given one."""
    params = dict(params)
    if model is not None:
        params[MODEL_PARAM] = model
    if MODEL_PARAM not in params:
        return params
    chosen = params[MODEL_PARAM]
    offered = generation_models(generator)
    if not offered.selectable:
        raise ValueError(
            f"the configured generator ({generator.name}) does not support choosing a model"
        )
    allowed = [choice.id for choice in offered.models]
    if chosen not in allowed:
        raise ValueError(f"unknown model {chosen!r}: expected one of {', '.join(allowed)}")
    return params


def _start(
    request: Request,
    background: BackgroundTasks,
    session: Session,
    settings: Settings,
    *,
    slug: str,
    kind: str,
    title: str,
    params: dict[str, Any],
    sources: list[tuple[KnowledgeSource, str]],
    model: str | None = None,
    supersedes: Artifact | None = None,
) -> ArtifactOut:
    """Create the artifact (`generating`), commit, schedule generation with the generator for
    its kind (`generator_for`); return its JSON. `model`, if given, is stored in the
    artifact's params and used to generate it."""
    generator = generator_for(request.app.state, kind)
    params = _params_with_model(generator, params, model)
    artifact = ArtifactManager(session, settings).create(
        slug=slug,
        kind=kind,
        title=title,
        generator=generator.name,
        params=params,
        sources=sources,
        supersedes=supersedes,
    )
    session.commit()  # the background job reads the artifact through its own sessions
    background.add_task(run_generation, settings, artifact.slug, generator)
    bank_builder = getattr(request.app.state, "review_bank_builder", None)
    if kind != LAB_KIND and bank_builder is not None:
        # Runs after the generation (background tasks run in order): the review queue's
        # variants of the new page's questions, if it is ready and has any (teacher.review_bank).
        background.add_task(
            build_after_generation, settings, artifact.slug, bank_builder, generator
        )
    return artifact_out(session, settings, artifact, request.app.state.max_attempts)


# -- endpoints ----------------------------------------------------------------------------


@router.post("/artifacts", status_code=202)
def create_artifact(
    body: ArtifactCreate,
    request: Request,
    background: BackgroundTasks,
    session: SessionDep,
    settings: SettingsDep,
) -> ArtifactOut:
    """Create an artifact from sources and generate it in the background."""
    source_manager = KnowledgeSourceManager(session, settings)
    sources = [source_manager.get_by_slug(slug) for slug in body.sources]
    title = body.title if body.title is not None else f"Study: {sources[0].title}"
    if body.slug is not None:
        slug = validate_slug(body.slug)
    else:
        slug = unique_slug(session, settings, slugify(title))
    out = _start(
        request,
        background,
        session,
        settings,
        slug=slug,
        kind=body.kind,
        title=title,
        params=body.params,
        sources=[(source, DEFAULT_ROLE) for source in sources],
        model=body.model,
    )
    StudyHistoryManager(session, settings).log(
        "study_page_requested",
        artifact=ArtifactManager(session, settings).get_by_slug(out.slug),
        payload={"sources": [source.slug for source in sources], "model": body.model},
    )
    return out


@router.get("/generation-models")
def list_generation_models(request: Request) -> GenerationModelsOut:
    """The models a study page can be generated with, and the default."""
    return generation_models(request.app.state.generator)


@router.get("/artifacts")
def list_artifacts(
    request: Request,
    session: SessionDep,
    settings: SettingsDep,
    source: Annotated[str | None, Query()] = None,
    status: Annotated[str | None, Query()] = None,
    kind: Annotated[str | None, Query()] = None,
) -> list[ArtifactOut]:
    linked = KnowledgeSourceManager(session, settings).get_by_slug(source) if source else None
    artifacts = ArtifactManager(session, settings).list(kind=kind, status=status, source=linked)
    max_attempts = request.app.state.max_attempts
    return [artifact_out(session, settings, a, max_attempts) for a in artifacts]


@router.get("/artifacts/{slug}")
def get_artifact(
    slug: str, request: Request, session: SessionDep, settings: SettingsDep
) -> ArtifactOut:
    artifact = ArtifactManager(session, settings).get_by_slug(slug)
    return artifact_out(session, settings, artifact, request.app.state.max_attempts)


@router.get("/artifacts/{slug}/runs")
def list_runs(slug: str, session: SessionDep, settings: SettingsDep) -> list[RunOut]:
    artifact = ArtifactManager(session, settings).get_by_slug(slug)
    return [run_out(run, settings) for run in GenerationRunManager(session, settings).list(artifact)]


@router.post("/artifacts/{slug}/regenerate", status_code=202)
def regenerate_artifact(
    slug: str,
    request: Request,
    background: BackgroundTasks,
    session: SessionDep,
    settings: SettingsDep,
    body: Annotated[RegenerateIn | None, Body()] = None,
) -> ArtifactOut:
    """Create a new artifact superseding `slug`, with the same kind, title and sources, and
    the same params and model unless the body gives new ones. A lab keeps its study page
    (`params.study_page`), which must still be a ready study page."""
    manager = ArtifactManager(session, settings)
    old = manager.get_by_slug(slug)
    _require_not_generating(old)
    params = dict(body.params if body is not None and body.params is not None else old.params or {})
    if old.kind == LAB_KIND:
        study_page = (old.params or {}).get(STUDY_PAGE_PARAM)
        if not isinstance(study_page, str):
            raise ValueError(f"lab {old.slug!r} names no study page, so it cannot be regenerated")
        if params.setdefault(STUDY_PAGE_PARAM, study_page) != study_page:
            raise ValueError(
                f"a regenerated lab keeps its study page {study_page!r}; make a lab of another "
                "page with POST /api/artifacts/{slug}/labs"
            )
        lab_study_page(session, settings, study_page, for_lab=old.slug)
    model = body.model if body is not None else None
    out = _start(
        request,
        background,
        session,
        settings,
        slug=unique_slug(session, settings, _lineage_root(old).slug),
        kind=old.kind,
        title=old.title,
        params=params,
        sources=manager.sources(old),
        model=model,
        supersedes=old,
    )
    new = manager.get_by_slug(out.slug)
    StudyHistoryManager(session, settings).log(
        "regeneration_requested",
        **({"lab": new} if new.kind == LAB_KIND else {"artifact": new}),
        payload={"supersedes": old.slug, "model": model},
    )
    return out


@router.delete("/artifacts/{slug}", status_code=204)
def delete_artifact(slug: str, session: SessionDep, settings: SettingsDep) -> Response:
    manager = ArtifactManager(session, settings)
    artifact = manager.get_by_slug(slug)
    _require_not_generating(artifact)
    StudyHistoryManager(session, settings).log(
        "artifact_deleted",
        **({"lab": artifact} if artifact.kind == LAB_KIND else {"artifact": artifact}),
        payload={"slug": artifact.slug, "title": artifact.title, "kind": artifact.kind},
    )
    manager.delete(artifact)
    return Response(status_code=204)


